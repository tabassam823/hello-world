-- Create a table for public proﬁles
create table profiles (
  id uuid references auth.users not null primary key,
  name text,
  email text
);
-- Set up Row Level Security (RLS)
-- See https://supabase.com/docs/guides/auth/row-level-security for more details.
alter table profiles
  enable row level security;

create policy "Public proﬁles are viewable by everyone." on profiles
  for select using (true);

create policy "Users can insert their own proﬁle." on profiles
  for insert with check (auth.uid() = id);

create policy "Users can update own proﬁle." on profiles
  for update using (auth.uid() = id);

-- This trigger automatically creates a proﬁle for new users.
-- See https://supabase.com/docs/guides/auth/managing-user-data#using-triggers for more details.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, email)
  values (new.id, new.raw_user_meta_data->>'name', new.email);
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();


-- Create notes table
create table notes (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  title text not null,
  content text,
  created_at timestamptz default now()
);

-- Set up RLS for notes table
alter table notes enable row level security;

create policy "Users can view their own notes." on notes
  for select using (auth.uid() = user_id);

create policy "Users can insert their own notes." on notes
  for insert with check (auth.uid() = user_id);

create policy "Users can update their own notes." on notes
  for update using (auth.uid() = user_id);

create policy "Users can delete their own notes." on notes
  for delete using (auth.uid() = user_id);


-- Create images table
create table images (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  title text not null,
  image_url text,
  created_at timestamptz default now()
);

-- Set up RLS for images table
alter table images enable row level security;

create policy "Users can view their own images." on images
  for select using (auth.uid() = user_id);

create policy "Users can insert their own images." on images
  for insert with check (auth.uid() = user_id);

create policy "Users can update their own images." on images
  for update using (auth.uid() = user_id);

create policy "Users can delete their own images." on images
  for delete using (auth.uid() = user_id);


-- Create shared_access table for sharing notes and images
create table shared_access (
  id bigint generated by default as identity primary key,
  note_id bigint references notes on delete cascade,
  image_id bigint references images on delete cascade,
  shared_with_user_id uuid references auth.users not null,
  created_at timestamptz default now(),
  constraint check_note_or_image_id
    check ( (note_id is not null and image_id is null) or (note_id is null and image_id is not null) )
);

-- Set up RLS for shared_access table
alter table shared_access enable row level security;

-- The owner of the note/image can grant access
create policy "Owners can grant access." on shared_access
  for insert with check (
    (note_id is not null and (select user_id from notes where id = note_id) = auth.uid()) or
    (image_id is not null and (select user_id from images where id = image_id) = auth.uid())
  );

-- The owner can see who they shared with
create policy "Owners can view grants." on shared_access
  for select using (
    (note_id is not null and (select user_id from notes where id = note_id) = auth.uid()) or
    (image_id is not null and (select user_id from images where id = image_id) = auth.uid())
  );

-- The recipient can see what's shared with them
create policy "Recipients can view grants." on shared_access
  for select using (shared_with_user_id = auth.uid());

-- Allow shared users to view the notes and images
create policy "Shared users can view notes." on notes
  for select using (
    id in (
      select note_id from shared_access where shared_with_user_id = auth.uid() and note_id is not null
    )
  );

create policy "Shared users can view images." on images
  for select using (
    id in (
      select image_id from shared_access where shared_with_user_id = auth.uid() and image_id is not null
    )
  );
